#!/usr/bin/env node

/**
 * Generates the browser's semantic theme palette from the exact Shiki catalog
 * and adaptive-variable algorithm consumed by desktop. Do not hand-edit the
 * generated output; run this script after changing desktop theme sources.
 */
import { createRequire } from "node:module";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const desktopRoot = path.join(root, "desktop");
const outputPath = path.join(
  root,
  "web",
  "src",
  "shared",
  "theme",
  "generated-desktop-theme-catalog.ts",
);
const desktopRequire = createRequire(
  pathToFileURL(path.join(desktopRoot, "package.json")),
);

const { bundledThemes } = await import(
  pathToFileURL(desktopRequire.resolve("shiki/themes")).href
);
const { createThemeVars } = await import(
  pathToFileURL(
    path.join(desktopRoot, "src", "shared", "theme", "adaptive-theme.ts"),
  ).href
);
const themeLoaderSource = await readFile(
  path.join(desktopRoot, "src", "shared", "theme", "theme-loader.ts"),
  "utf8",
);
const themeList = /export const SYNTAX_THEMES = \[(.*?)\] as const;/s.exec(
  themeLoaderSource,
);
if (!themeList) {
  throw new Error("Could not read the desktop SYNTAX_THEMES catalog.");
}
const SYNTAX_THEMES = [...themeList[1].matchAll(/"([^"]+)"/g)].map(
  ([, name]) => name,
);
const pairList = /export const THEME_PAIRS:[\s\S]*?new Map\(\[(.*?)\]\);/s.exec(
  themeLoaderSource,
);
if (!pairList) {
  throw new Error("Could not read the desktop THEME_PAIRS catalog.");
}
const pairs = Object.fromEntries(
  [...pairList[1].matchAll(/\["([^"]+)", "([^"]+)"\]/g)].map(
    ([, from, to]) => [from, to],
  ),
);

function extractCommentColor(settings, fallback) {
  for (const setting of settings ?? []) {
    if (!setting.scope || !setting.settings?.foreground) continue;
    const scopes = Array.isArray(setting.scope)
      ? setting.scope
      : [setting.scope];
    if (scopes.includes("comment")) return setting.settings.foreground;
  }
  return fallback;
}

function stripAlpha(color) {
  return color?.length === 9 && color.startsWith("#")
    ? color.slice(0, 7)
    : color;
}

function extractGitColors(colors) {
  const find = (keys) => {
    for (const key of keys) {
      if (colors?.[key]) return stripAlpha(colors[key]);
    }
    return null;
  };
  return {
    added: find([
      "gitDecoration.addedResourceForeground",
      "editorGutter.addedBackground",
      "diffEditor.insertedTextBackground",
    ]),
    deleted: find([
      "gitDecoration.deletedResourceForeground",
      "editorGutter.deletedBackground",
      "diffEditor.removedTextBackground",
    ]),
    modified: find([
      "gitDecoration.modifiedResourceForeground",
      "editorGutter.modifiedBackground",
    ]),
  };
}

function extractThemeInfo(theme) {
  const colors = theme.colors ?? {};
  const foreground = colors["editor.foreground"] ?? "#d4d4d4";
  return {
    bg: colors["editor.background"] ?? "#1e1e1e",
    fg: foreground,
    comment: extractCommentColor(theme.settings, foreground),
    ...extractGitColors(colors),
  };
}

const catalog = {};
for (const name of SYNTAX_THEMES) {
  const sourceName =
    name === "buzz"
      ? "github-light"
      : name === "buzz-dark"
        ? "github-dark"
        : name;
  const loader = bundledThemes[sourceName];
  if (!loader) {
    throw new Error(`Desktop theme ${name} has no Shiki source: ${sourceName}`);
  }
  const { default: source } = await loader();
  const info = extractThemeInfo(source);
  const { isDark, vars } = createThemeVars(info.bg, info.fg, info.comment, {
    added: info.added,
    deleted: info.deleted,
    modified: info.modified,
  });
  catalog[name] = { isDark, pairedTheme: pairs[name] ?? null, vars };
}

const output = `// Generated by scripts/generate-web-theme-catalog.mjs from desktop's Shiki catalog.\n// Do not hand-edit.\n\nexport type DesktopThemePalette = {\n  isDark: boolean;\n  pairedTheme: string | null;\n  vars: Record<string, string>;\n};\n\nconst serializedCatalog = ${JSON.stringify(JSON.stringify(catalog))};\n\nexport const DESKTOP_THEME_CATALOG: Readonly<\n  Record<string, DesktopThemePalette>\n> = JSON.parse(serializedCatalog) as Record<string, DesktopThemePalette>;\n`;

if (process.argv.includes("--check")) {
  const current = await readFile(outputPath, "utf8").catch(() => "");
  if (current !== output) {
    console.error(
      "Web's generated desktop theme catalog is stale. Run: node --experimental-strip-types scripts/generate-web-theme-catalog.mjs",
    );
    process.exitCode = 1;
  }
} else {
  await writeFile(outputPath, output);
}
